export async function initializeI18n() {
  I18nManager.allowRTL(true);
  const savedLanguage = await AsyncStorage.getItem(LANGUAGE_KEY);
  const language: AppLanguage =
    savedLanguage === 'ar' || savedLanguage === 'en' ? savedLanguage : DEFAULT_LANGUAGE;
  if (!i18n.isInitialized) {
    await i18n.use(initReactI18next).init({
      resources,
      lng: language,
      fallbackLng: DEFAULT_LANGUAGE,
      supportedLngs: ['ar', 'en'],
      interpolation: { escapeValue: false },
    });
  } else if (i18n.language !== language) {
    await i18n.changeLanguage(language);
  }

  applyWebDirection(language);
  logDirection('startup', language);
  if (Platform.OS !== 'web' && await synchronizeNativeDirection(language)) {
    await reloadAppAsync();
  }
  return i18n;
}

export async function changeAppLanguage(language: AppLanguage) {
  await i18n.changeLanguage(language);
  await AsyncStorage.setItem(LANGUAGE_KEY, language);

  if (Platform.OS === 'web') {
    applyWebDirection(language);
    return;
  }

  logDirection('language switch', language);
  if (await synchronizeNativeDirection(language)) {
    await reloadAppAsync();
  }
}

export function getAppDirection(language: string): AppDirection {
  return language.startsWith('ar') ? 'rtl' : 'ltr';
}

async function synchronizeNativeDirection(language: AppLanguage) {
  const shouldUseRtl = language === 'ar';
  const reloadKey = getDirectionReloadKey();
  const pendingDirection = await AsyncStorage.getItem(reloadKey);

  if (I18nManager.isRTL !== shouldUseRtl) {
    I18nManager.forceRTL(shouldUseRtl);

    if (pendingDirection === language) {
      logDirection('reload already attempted', language);
      return false;
    }

    await AsyncStorage.setItem(reloadKey, language);
    logDirection('reload requested', language, true);
    return true;
  }

  if (pendingDirection) {
    await AsyncStorage.removeItem(reloadKey);
  }
  await AsyncStorage.removeItem(LEGACY_DIRECTION_RELOAD_KEY);

  return false;
}

function getDirectionReloadKey() {
  const runtime = Constants.appOwnership ?? Constants.executionEnvironment ?? 'unknown';
  return `${DIRECTION_RELOAD_KEY_PREFIX}.${runtime}`;
}

function logDirection(stage: string, language: AppLanguage, reloadRequested = false) {
  if (!__DEV__) return;

  console.log('[RTL DEBUG]', {
    platform: Platform.OS,
    stage,
    language,
    isRTL: I18nManager.isRTL,
    expectedRTL: language === 'ar',
    reloadRequested,
  });
}

function applyWebDirection(language: AppLanguage) {
  if (Platform.OS === 'web' && typeof document !== 'undefined') {
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = language;
  }
}

